'use strict';

/**
 * House override statements — Excel export.
 *
 * THEI / BSI 50/50, Marco $10 peel, Integrity producer shares.
 * Lina's agent producer_payable is NOT on these statements.
 */

const ExcelJS = require('exceljs');
const { STATEMENT_TYPES } = require('./payeeSchedules');
const { formatEffectiveDate } = require('./effectiveDateFormat');
const { houseStatementLabel, houseStatementFilename, safeSheetName } = require('./houseStatementNames');
const { MONEY_FMT, writeMoneyCell, writeLabeledMoney, round2 } = require('./statementExcelTotals');

/** Header block rows. Line table starts after Period + totals + a blank row. */
const LINE_HEADER_ROW = 11;
const FIRST_LINE_ROW = 12;

function formatReportDate(d = new Date()) {
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  const yyyy = d.getFullYear();
  return `${mm}/${dd}/${yyyy}`;
}

function titleFor(type) {
  // THEI. NHP Statement / THEI. BSI Statement / BSI Medicare Overrides
  if (houseStatementLabel(type)) return houseStatementLabel(type);
  if (type === STATEMENT_TYPES.MARCO) return 'Marco (Swan) Override Statement';
  if (type === STATEMENT_TYPES.INTEGRITY) return 'Integrity Partners Producer Statement';
  return 'THEI Override Statement';
}

function noteFor(type) {
  if (type === STATEMENT_TYPES.BSI_OVERRIDE) {
    return 'BSI 50% of Agency Override pot + Alba rate-peeled production shares. Not agent commissions.';
  }
  if (type === STATEMENT_TYPES.THEI_NHP) {
    return 'THEI share of NHP agency statement sales / overrides only. Direct-carrier and BSI remittance are on the BSI remittance report.';
  }
  if (type === STATEMENT_TYPES.THEI_BSI) {
    return 'THEI share of what BSI pays us (BSI remittance / BSI payee feeds). NHP sales are on the NHP report.';
  }
  if (type === STATEMENT_TYPES.MARCO) {
    return '$10 per policy agency peel (Swan / Marco) across downline. Not an agent commission.';
  }
  if (type === STATEMENT_TYPES.INTEGRITY) {
    return 'Integrity / CAM / Chris 50% producer share. THEI 25% and BSI 25% are on house override statements.';
  }
  return 'THEI 50% of Agency Override pot + Alba rate-peeled production shares. Not agent commissions.';
}

/** Line-table headers — same layout on every house statement (THEI, BSI, Marco, Integrity). */
const LINE_HEADERS = [
  'Policy #',
  'Client',
  'Carrier',
  'Writing Agent',
  'Effective',
  'Type',
  'Total Override',
  'Payable',
];

function footerFor(type) {
  if (type === STATEMENT_TYPES.MARCO) {
    return 'Generated by OliComm · Marco $10/policy peel · Lina agent pay is a separate statement';
  }
  if (type === STATEMENT_TYPES.INTEGRITY) {
    return 'Generated by OliComm · Integrity 50% producer · THEI/BSI 25% each on house statements · Lina agent pay is separate';
  }
  return 'Generated by OliComm · THEI/BSI are 50/50 of override · Lina agent pay is a separate statement';
}

/**
 * Build Excel workbook for one override payee statement (from buildOverrideStatements).
 */
async function buildOverrideExcelWorkbook(bundle, payeeStatement, opts = {}) {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'OliComm';
  wb.created = new Date();

  const ws = wb.addWorksheet(sheetNameFor(bundle.type), {
    views: [{ showGridLines: false }],
  });

  ws.columns = [
    { key: 'policy', width: 18 },
    { key: 'client', width: 28 },
    { key: 'carrier', width: 18 },
    { key: 'agent', width: 28 },
    { key: 'effective', width: 14 },
    { key: 'type', width: 16 },
    { key: 'pot', width: 14 },
    { key: 'amount', width: 14 },
  ];

  const titleStyle = { font: { bold: true, size: 14, color: { argb: 'FF1A1A1A' } } };
  const mutedStyle = { font: { size: 11, color: { argb: 'FF64748B' } } };
  const headerStyle = {
    font: { bold: true, size: 11, color: { argb: 'FF334155' } },
    fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF1F5F9' } },
    border: { bottom: { style: 'thin', color: { argb: 'FFCBD5E1' } } },
  };
  const reportDate = opts.reportDate || formatReportDate(opts.now || new Date());

  const sorted = [...(payeeStatement.lines || [])].sort((a, b) => {
    const ca = String(a.carrier || '').localeCompare(String(b.carrier || ''));
    if (ca) return ca;
    return String(a.policy_number || '').localeCompare(String(b.policy_number || ''));
  });
  const payableTotal = round2(payeeStatement.total);
  const overrideTotal = round2(sorted.reduce((s, l) => s + (Number(l.override_pot) || 0), 0));

  ws.mergeCells('A1:H1');
  ws.getCell('A1').value = titleFor(bundle.type);
  ws.getCell('A1').style = titleStyle;

  ws.mergeCells('A2:H2');
  ws.getCell('A2').value = `${bundle.periodLabel} Statement`;
  ws.getCell('A2').style = { font: { bold: true, size: 12 } };

  ws.getCell('A4').value = 'Report Date';
  ws.getCell('A4').style = mutedStyle;
  ws.getCell('B4').value = reportDate;

  ws.getCell('A5').value = 'Payee';
  ws.getCell('A5').style = mutedStyle;
  ws.getCell('B5').value = payeeStatement.payee;

  ws.getCell('A6').value = 'Issued By';
  ws.getCell('A6').style = mutedStyle;
  ws.getCell('B6').value = 'The Health Experts Insurance · OliComm';

  ws.getCell('A7').value = 'Period';
  ws.getCell('A7').style = mutedStyle;
  ws.getCell('B7').value = bundle.periodLabel;

  writeLabeledMoney(ws, 8, 'Total Payable', payableTotal, { labelStyle: mutedStyle });
  writeLabeledMoney(ws, 9, 'Total Override', overrideTotal, { labelStyle: mutedStyle });

  const headerRow = ws.getRow(LINE_HEADER_ROW);
  LINE_HEADERS.forEach((h, i) => {
    const cell = headerRow.getCell(i + 1);
    cell.value = h;
    cell.style = headerStyle;
  });

  let rowIdx = FIRST_LINE_ROW;
  for (const l of sorted) {
    const row = ws.getRow(rowIdx);
    row.getCell(1).value = l.policy_number || '';
    row.getCell(2).value = l.client_full_name || '';
    row.getCell(3).value = l.carrier || '';
    row.getCell(4).value = l.writing_agent || l.agent_name || '';
    row.getCell(5).value = formatEffectiveDate(l.effective_date);
    row.getCell(6).value = l.classification || '';
    writeMoneyCell(row.getCell(7), l.override_pot);
    writeMoneyCell(row.getCell(8), l.amount);
    rowIdx += 1;
  }

  const totalRow = ws.getRow(rowIdx);
  totalRow.getCell(1).value = 'TOTAL';
  totalRow.getCell(1).font = { bold: true };
  writeMoneyCell(totalRow.getCell(7), overrideTotal, { bold: true });
  writeMoneyCell(totalRow.getCell(8), payableTotal, { bold: true });
  rowIdx += 2;

  const gross = round2(sorted.filter((l) => l.amount > 0).reduce((s, l) => s + l.amount, 0));
  const chargebacks = round2(sorted.filter((l) => l.amount < 0).reduce((s, l) => s + l.amount, 0));
  const balance = payableTotal;

  ws.getCell(`A${rowIdx}`).value = 'Gross';
  ws.getCell(`A${rowIdx}`).font = { bold: true };
  writeMoneyCell(ws.getCell(`H${rowIdx}`), gross);
  rowIdx += 1;

  ws.getCell(`A${rowIdx}`).value = 'Chargebacks / negatives';
  ws.getCell(`A${rowIdx}`).font = { bold: true };
  writeMoneyCell(ws.getCell(`H${rowIdx}`), chargebacks);
  rowIdx += 1;

  ws.getCell(`A${rowIdx}`).value = 'Balance due payee';
  ws.getCell(`A${rowIdx}`).font = { bold: true, size: 12 };
  writeMoneyCell(ws.getCell(`H${rowIdx}`), balance, { bold: true, size: 12 });

  rowIdx += 2;
  ws.mergeCells(`A${rowIdx}:H${rowIdx}`);
  ws.getCell(`A${rowIdx}`).value = footerFor(bundle.type);
  ws.getCell(`A${rowIdx}`).style = mutedStyle;

  const sum = wb.addWorksheet('Summary');
  sum.columns = [
    { key: 'k', width: 28 },
    { key: 'v', width: 40 },
  ];
  [
    ['Statement', titleFor(bundle.type)],
    ['Payee', payeeStatement.payee],
    ['Report Date', reportDate],
    ['Period', bundle.periodLabel],
    ['Total Payable', payableTotal],
    ['Total Override', overrideTotal],
    ['Line Count', sorted.length],
    ['Gross', gross],
    ['Chargebacks / negatives', chargebacks],
    ['Balance due payee', balance],
  ].forEach((pair, i) => {
    sum.getCell(`A${i + 1}`).value = pair[0];
    sum.getCell(`A${i + 1}`).font = { bold: true };
    sum.getCell(`B${i + 1}`).value = pair[1];
    if (i >= 4 && i !== 6) sum.getCell(`B${i + 1}`).numFmt = MONEY_FMT;
  });

  return wb;
}

/** First sheet name: the statement name for the renamed house types, else 'Override Statement'. */
function sheetNameFor(type) {
  return houseStatementLabel(type) ? safeSheetName(houseStatementLabel(type)) : 'Override Statement';
}

function filenameForOverrideExcel(bundle, payee) {
  const renamed = houseStatementFilename(bundle.type, bundle.period, 'xlsx');
  if (renamed) return renamed;
  const periodPart =
    bundle.period && bundle.period !== 'all' ? bundle.period : 'ALL';
  const who =
    bundle.type === STATEMENT_TYPES.BSI_OVERRIDE
      ? 'BSI'
      : bundle.type === STATEMENT_TYPES.THEI_NHP
        ? 'THEI_NHP'
        : bundle.type === STATEMENT_TYPES.THEI_BSI
          ? 'THEI_BSI_Remittance'
          : bundle.type === STATEMENT_TYPES.THEI_OVERRIDE
        ? 'THEI'
        : bundle.type === STATEMENT_TYPES.MARCO
          ? 'Marco'
          : String(payee || 'Override').replace(/\s+/g, '_').replace(/[^A-Za-z0-9_\-]/g, '');
  return `${who}_Override_Statement_${periodPart}.xlsx`;
}

module.exports = {
  buildOverrideExcelWorkbook,
  filenameForOverrideExcel,
  formatReportDate,
  titleFor,
  sheetNameFor,
  noteFor,
  LINE_HEADERS,
  LINE_HEADER_ROW,
  FIRST_LINE_ROW,
};
